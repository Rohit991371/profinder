from __future__ import annotations

from pathlib import Path

import yaml

from .merge import Merged, Seed
from .textnorm import host_of, registrable_domain


def build_domains(merged: list[Merged], seeds: list[Seed]) -> dict:
    """Allow-list per university. Registry-derived registrable domain + hand-added domains. email_domains adds CERNET-style extras."""
    seed_by = {s.name: s for s in seeds}
    out: dict = {}
    for m in merged:
        s = seed_by[m.name]
        reg = []
        d = registrable_domain(m.official_url)
        if d and not any(f.startswith("url_domain_conflict") for f in m.flags):
            reg.append(d)
        doms = sorted({*reg, *(host_of(x) or x for x in s.domains), *(host_of(x) or x for x in s.extra_domains)})
        email = sorted({*reg, *s.extra_email_domains, *(d for d in map(registrable_domain, s.domains) if d)})
        out[m.name] = {
            "domains": doms,
            "email_domains": email,
            "from_registry": reg,
            "status": m.status,
        }
    return out


def dump_domains(data: dict, path: Path) -> None:
    hdr = ("# Generated by `python -m profinder_pipeline.registry build --write-domains`. Do not edit by hand:\n"
           "# add hand-made entries under extra_domains / extra_email_domains in config/universities.yml.\n"
           "# A host is allowed when it equals a domain below or is a sub-domain of it.\n")
    path.write_text(hdr + yaml.safe_dump({"universities": data}, allow_unicode=True, sort_keys=False, width=200), encoding="utf-8")
